#!/usr/bin/env python3
"""Replay fixed CALVIN demonstration action scripts and collect oracle-gated simulator rollouts.

The source demonstrations provide only the reproducible relative-action script and
exact reset state. Every saved observation is freshly generated by the simulator.
A rollout is placed in ``accepted/`` only when CALVIN's task oracle confirms the
requested task; failed attempts remain separately auditable under ``attempts/``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
from typing import Any

import numpy as np


TASK_SPECS: dict[str, dict[str, Any]] = {
    "push_blue_block_left": {
        "family": "block_push",
        "source_start": 20390,
        "source_end": 20425,
        "progress_index": 12,
        "flow": [-1.0, 0.0, 0.0],
    },
    "open_drawer": {
        "family": "drawer",
        "source_start": 49591,
        "source_end": 49655,
        "progress_index": 1,
        "flow": [0.07135061, -0.9931737, 0.09227731],
    },
    "move_slider_left": {
        "family": "slider",
        "source_start": 113269,
        "source_end": 113333,
        "progress_index": 0,
        "flow": [-0.99983954, 0.00174157, 0.01782997],
    },
}

REQUIRED_STEP_FIELDS = (
    "robot_obs",
    "scene_obs",
    "rgb_static",
    "rgb_gripper",
    "actions",
)
PROVISIONAL_STEP_FIELDS = ("g", "phase", "post_contact")


def json_default(value: Any) -> Any:
    if isinstance(value, Path):
        return value.as_posix()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    raise TypeError(f"Cannot JSON encode {type(value)!r}")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def task_progress(task: str, initial_scene: np.ndarray, current_scene: np.ndarray) -> float:
    """Return signed oracle-relevant progress from the exact reset state."""

    if task not in TASK_SPECS:
        raise KeyError(f"Unsupported scripted task: {task}")
    initial = np.asarray(initial_scene, dtype=np.float32)
    current = np.asarray(current_scene, dtype=np.float32)
    if initial.shape != (24,) or current.shape != (24,):
        raise ValueError("CALVIN scene observations must have shape (24,)")
    index = int(TASK_SPECS[task]["progress_index"])
    delta = float(current[index] - initial[index])
    if task == "push_blue_block_left":
        return -delta
    return delta


def build_guidance(
    task: str,
    robot_obs: np.ndarray,
    initial_scene: np.ndarray,
    current_scene: np.ndarray,
    interaction_anchor: np.ndarray,
    *,
    motion_threshold: float,
) -> dict[str, Any]:
    """Build state-grounded phase and compact ``G=[A,F]`` for one step."""

    progress = task_progress(task, initial_scene, current_scene)
    post_contact = bool(progress >= motion_threshold)
    robot = np.asarray(robot_obs, dtype=np.float32)
    anchor = np.asarray(interaction_anchor, dtype=np.float32)
    if robot.shape != (15,) or anchor.shape != (3,):
        raise ValueError("Expected robot_obs (15,) and interaction_anchor (3,)")
    attraction = np.zeros(3, dtype=np.float32) if post_contact else anchor - robot[:3]
    flow = np.asarray(TASK_SPECS[task]["flow"], dtype=np.float32)
    flow /= max(float(np.linalg.norm(flow)), 1e-8)
    return {
        "g": np.concatenate([attraction, flow]).astype(np.float32),
        "phase": "contact_transport" if post_contact else "approach",
        "post_contact": post_contact,
        "progress": progress,
    }


def validate_trajectory(trajectory: dict[str, Any]) -> None:
    """Validate native rollout data; candidate G labels are optional and versioned."""

    missing = [name for name in REQUIRED_STEP_FIELDS if name not in trajectory]
    if missing:
        raise ValueError(f"Missing trajectory fields: {missing}")
    present = [name for name in PROVISIONAL_STEP_FIELDS if name in trajectory]
    schema = str(np.asarray(trajectory.get("provisional_label_schema", "legacy_unversioned_g")).item())
    if schema in {"not_emitted", "native_only_v1"} and present:
        raise ValueError(f"Provisional labels present while schema={schema}")
    if schema == "legacy_unversioned_g" and present and len(present) != len(PROVISIONAL_STEP_FIELDS):
        raise ValueError(f"Legacy provisional label bundle is incomplete: {present}")
    if schema not in {"not_emitted", "native_only_v1", "legacy_unversioned_g"} and len(present) != len(PROVISIONAL_STEP_FIELDS):
        raise ValueError(f"Versioned provisional label bundle is incomplete: {present}")
    if not present and schema not in {"not_emitted", "native_only_v1"}:
        raise ValueError(f"Provisional labels absent but schema is {schema!r}")
    temporal = REQUIRED_STEP_FIELDS + (("progress",) if "progress" in trajectory else ()) + tuple(present)
    lengths = {name: len(np.asarray(trajectory[name])) for name in temporal}
    if len(set(lengths.values())) != 1:
        raise ValueError(f"Step modalities must be aligned: {lengths}")
    steps = next(iter(lengths.values()))
    if steps < 1:
        raise ValueError("Trajectory must contain at least one step")
    expected_shapes = {
        "robot_obs": (steps, 15),
        "scene_obs": (steps, 24),
        "actions": (steps, 7),
    }
    if "g" in trajectory:
        expected_shapes["g"] = (steps, 6)
    for name, expected in expected_shapes.items():
        if np.asarray(trajectory[name]).shape != expected:
            raise ValueError(f"Unexpected {name} shape: {np.asarray(trajectory[name]).shape}; expected {expected}")
    for name in ("rgb_static", "rgb_gripper"):
        value = np.asarray(trajectory[name])
        if value.ndim != 4 or value.shape[0] != steps or value.shape[-1] != 3:
            raise ValueError(f"Unexpected {name} shape: {value.shape}")
    if "phase" in trajectory:
        phases = np.asarray(trajectory["phase"]).astype(str)
        if not set(phases.tolist()) <= {"approach", "contact_transport"}:
            raise ValueError(f"Unexpected phase values: {sorted(set(phases.tolist()))}")
        post_contact = np.asarray(trajectory["post_contact"], dtype=bool)
        if not np.array_equal(post_contact, phases == "contact_transport"):
            raise ValueError("phase and post_contact are not aligned")


def persist_attempt(
    output_root: Path,
    *,
    attempt_id: str,
    trajectory: dict[str, Any],
    receipt: dict[str, Any],
) -> Path:
    """Persist success to accepted/ and failure only to attempts/."""

    validate_trajectory(trajectory)
    oracle_success = bool(receipt.get("oracle_success", False))
    trajectory_success = bool(np.asarray(trajectory.get("success", False)).item())
    if oracle_success != trajectory_success:
        raise ValueError("Trajectory success must match oracle receipt")
    bucket = "accepted" if oracle_success else "attempts"
    directory = Path(output_root) / bucket
    directory.mkdir(parents=True, exist_ok=True)
    npz_path = directory / f"{attempt_id}.npz"
    receipt_path = directory / f"{attempt_id}.receipt.json"
    if npz_path.exists() or receipt_path.exists():
        raise FileExistsError(f"Refusing to overwrite existing attempt: {attempt_id}")
    tmp_npz = directory / f".{attempt_id}.npz.tmp"
    with open(tmp_npz, "wb") as stream:
        np.savez_compressed(stream, **trajectory)
    os.replace(tmp_npz, npz_path)
    receipt_payload = dict(receipt)
    receipt_payload["trajectory"] = npz_path.relative_to(output_root).as_posix()
    receipt_payload["trajectory_sha256"] = sha256_file(npz_path)
    tmp_receipt = directory / f".{attempt_id}.receipt.json.tmp"
    with open(tmp_receipt, "w", encoding="utf-8") as stream:
        json.dump(receipt_payload, stream, indent=2, default=json_default)
        stream.write("\n")
    os.replace(tmp_receipt, receipt_path)
    return npz_path


def persist_failure_metadata_only(
    output_root: Path,
    *,
    attempt_id: str,
    receipt: dict[str, Any],
) -> Path:
    if bool(receipt.get("oracle_success", False)):
        raise ValueError("metadata-only persistence is only valid for failed attempts")
    directory = Path(output_root) / "failures"
    directory.mkdir(parents=True, exist_ok=True)
    receipt_path = directory / f"{attempt_id}.receipt.json"
    if receipt_path.exists():
        raise FileExistsError(f"Refusing to overwrite existing failure receipt: {attempt_id}")
    payload = dict(receipt)
    payload.update({"failure_storage_mode": "metadata_only", "trajectory": None, "trajectory_sha256": None})
    tmp_receipt = directory / f".{attempt_id}.receipt.json.tmp"
    with open(tmp_receipt, "w", encoding="utf-8") as stream:
        json.dump(payload, stream, indent=2, default=json_default)
        stream.write("\n")
    os.replace(tmp_receipt, receipt_path)
    return receipt_path


def validate_collection(output_root: Path) -> dict[str, Any]:
    """Read a completed collection back from disk and verify gates, hashes, and schema."""

    root = Path(output_root)
    manifest_path = root / "collection_manifest.json"
    with open(manifest_path, encoding="utf-8") as stream:
        manifest = json.load(stream)
    if manifest.get("format") != "calvin_scripted_expert_collection_v1":
        raise ValueError(f"Unexpected collection format: {manifest.get('format')!r}")
    rows = list(manifest.get("results", []))
    accepted_verified = 0
    tasks: list[str] = []
    details: list[dict[str, Any]] = []
    for row in rows:
        oracle_success = bool(row.get("oracle_success", False))
        if not row.get("path"):
            if oracle_success:
                raise ValueError("Accepted scripted trajectory cannot omit path")
            receipt_rel = row.get("receipt_path")
            if row.get("failure_storage_mode") != "metadata_only" or not receipt_rel:
                raise ValueError("Failed scripted row without payload must provide metadata-only receipt")
            receipt_path = root / str(receipt_rel)
            with open(receipt_path, encoding="utf-8") as stream:
                receipt = json.load(stream)
            if bool(receipt.get("oracle_success", True)):
                raise ValueError(f"Metadata-only failure receipt is not failed: {receipt_path}")
            details.append({"task": str(row["task"]), "oracle_success": False, "steps": 0, "phase_counts": {}, "receipt": receipt_rel})
            continue
        relative_path = Path(row["path"])
        expected_bucket = "accepted" if oracle_success else "attempts"
        if not relative_path.parts or relative_path.parts[0] != expected_bucket:
            raise ValueError(f"Success gate/path mismatch for {relative_path}")
        path = root / relative_path
        if sha256_file(path) != row["sha256"]:
            raise ValueError(f"SHA-256 mismatch: {path}")
        receipt_path = path.with_suffix(".receipt.json")
        with open(receipt_path, encoding="utf-8") as stream:
            receipt = json.load(stream)
        if bool(receipt.get("oracle_success", False)) != oracle_success:
            raise ValueError(f"Manifest/receipt oracle mismatch: {path}")
        if receipt.get("trajectory_sha256") != row["sha256"]:
            raise ValueError(f"Receipt/trajectory hash mismatch: {path}")
        with np.load(path, allow_pickle=False) as payload:
            trajectory = {name: payload[name] for name in payload.files}
        validate_trajectory(trajectory)
        if bool(np.asarray(trajectory.get("success", False)).item()) != oracle_success:
            raise ValueError(f"Stored success/oracle mismatch: {path}")
        task = str(np.asarray(trajectory["task"]).item())
        if task != str(row["task"]):
            raise ValueError(f"Stored task/manifest mismatch: {path}")
        if "phase" in trajectory:
            phases, counts = np.unique(np.asarray(trajectory["phase"]).astype(str), return_counts=True)
            phase_counts = {phase: int(count) for phase, count in zip(phases, counts)}
        else:
            phase_counts = {}
        details.append(
            {
                "task": task,
                "oracle_success": oracle_success,
                "steps": int(len(trajectory["actions"])),
                "phase_counts": phase_counts,
                "rgb_static_shape": list(np.asarray(trajectory["rgb_static"]).shape),
                "rgb_gripper_shape": list(np.asarray(trajectory["rgb_gripper"]).shape),
                "sha256": row["sha256"],
            }
        )
        if oracle_success:
            accepted_verified += 1
            tasks.append(task)
    if accepted_verified != int(manifest.get("accepted", -1)):
        raise ValueError("Manifest accepted count does not match verified artifacts")
    failed_verified = len(rows) - accepted_verified
    if failed_verified != int(manifest.get("failed", -1)):
        raise ValueError("Manifest failed count does not match verified artifacts")
    return {
        "manifest": manifest_path,
        "accepted_verified": accepted_verified,
        "failed_verified": failed_verified,
        "tasks": sorted(tasks),
        "details": details,
    }


def source_frame_path(split_dir: Path, frame_id: int) -> Path:
    return split_dir / f"episode_{frame_id:07d}.npz"


def load_source_script(split_dir: Path, task: str, motion_threshold: float) -> dict[str, Any]:
    """Load a fixed reset plus official relative actions and calibrate interaction anchor."""

    spec = TASK_SPECS[task]
    start, end = int(spec["source_start"]), int(spec["source_end"])
    frames = []
    for frame_id in range(start, end + 1):
        path = source_frame_path(split_dir, frame_id)
        if not path.is_file():
            raise FileNotFoundError(path)
        with np.load(path) as payload:
            frames.append(
                {
                    "frame_id": frame_id,
                    "robot_obs": np.asarray(payload["robot_obs"], dtype=np.float32).copy(),
                    "scene_obs": np.asarray(payload["scene_obs"], dtype=np.float32).copy(),
                    "rel_actions": np.asarray(payload["rel_actions"], dtype=np.float32).copy(),
                }
            )
    initial_scene = frames[0]["scene_obs"]
    interaction_index = next(
        (
            index
            for index, frame in enumerate(frames)
            if task_progress(task, initial_scene, frame["scene_obs"]) >= motion_threshold
        ),
        None,
    )
    if interaction_index is None:
        raise RuntimeError(f"Source script never reaches motion threshold for {task}")
    anchor_index = max(0, interaction_index - 1)
    return {
        "initial_robot_obs": frames[0]["robot_obs"],
        "initial_scene_obs": initial_scene,
        "actions": np.stack([frame["rel_actions"] for frame in frames]),
        "source_frame_ids": np.asarray([frame["frame_id"] for frame in frames], dtype=np.int64),
        "interaction_anchor": frames[anchor_index]["robot_obs"][:3].copy(),
        "source_interaction_index": int(interaction_index),
    }


def stack_steps(steps: list[dict[str, Any]], metadata: dict[str, Any]) -> dict[str, Any]:
    trajectory = {
        name: np.stack([np.asarray(step[name]) for step in steps])
        for name in ("robot_obs", "scene_obs", "rgb_static", "rgb_gripper", "actions", "progress")
    }
    presence = {name: all(name in step for step in steps) for name in PROVISIONAL_STEP_FIELDS}
    if any(presence.values()) and not all(presence.values()):
        raise ValueError(f"Provisional label fields must be emitted together: {presence}")
    if all(presence.values()):
        trajectory["g"] = np.stack([np.asarray(step["g"]) for step in steps])
        trajectory["phase"] = np.asarray([step["phase"] for step in steps])
        trajectory["post_contact"] = np.asarray([step["post_contact"] for step in steps], dtype=bool)
    for name, value in metadata.items():
        trajectory[name] = np.asarray(value)
    validate_trajectory(trajectory)
    return trajectory


def collect_one(
    env: Any,
    oracle: Any,
    split_dir: Path,
    task: str,
    motion_threshold: float,
    *,
    emit_provisional_g: bool = False,
) -> tuple[dict[str, Any], dict[str, Any]]:
    script = load_source_script(split_dir, task, motion_threshold)
    obs = env.reset(robot_obs=script["initial_robot_obs"], scene_obs=script["initial_scene_obs"])
    start_info = env.get_info()
    steps: list[dict[str, Any]] = []
    achieved: list[str] = []
    success_step: int | None = None
    for index, action in enumerate(script["actions"]):
        guidance = build_guidance(
            task,
            np.asarray(obs["robot_obs"], dtype=np.float32),
            script["initial_scene_obs"],
            np.asarray(obs["scene_obs"], dtype=np.float32),
            script["interaction_anchor"],
            motion_threshold=motion_threshold,
        )
        rgb_obs = obs.get("rgb_obs", {})
        step = {
            "robot_obs": np.asarray(obs["robot_obs"], dtype=np.float32).copy(),
            "scene_obs": np.asarray(obs["scene_obs"], dtype=np.float32).copy(),
            "rgb_static": np.asarray(rgb_obs["rgb_static"], dtype=np.uint8).copy(),
            "rgb_gripper": np.asarray(rgb_obs["rgb_gripper"], dtype=np.uint8).copy(),
            "actions": np.asarray(action, dtype=np.float32).copy(),
            "progress": guidance["progress"],
        }
        if emit_provisional_g:
            step.update({name: guidance[name] for name in PROVISIONAL_STEP_FIELDS})
        steps.append(step)
        obs, _, _, current_info = env.step(action)
        achieved = sorted(oracle.get_task_info_for_set(start_info, current_info, {task}))
        if task in achieved:
            success_step = index
            break
    success = success_step is not None
    final_progress = task_progress(task, script["initial_scene_obs"], np.asarray(obs["scene_obs"], dtype=np.float32))
    trajectory = stack_steps(
        steps,
        {
            "task": task,
            "success": success,
            "provisional_label_schema": "candidate_g_af_v1" if emit_provisional_g else "not_emitted",
            "source_kind": "official_demonstration_relative_action_script_replayed_in_simulator",
            "source_start": TASK_SPECS[task]["source_start"],
            "source_end": TASK_SPECS[task]["source_end"],
            "source_frame_ids": script["source_frame_ids"][: len(steps)],
            "reset_robot_obs": script["initial_robot_obs"],
            "reset_scene_obs": script["initial_scene_obs"],
            "interaction_anchor": script["interaction_anchor"],
        },
    )
    receipt = {
        "task": task,
        "family": TASK_SPECS[task]["family"],
        "oracle_success": success,
        "oracle_achieved_tasks": achieved,
        "success_step": success_step,
        "executed_steps": len(steps),
        "final_progress": final_progress,
        "motion_threshold": motion_threshold,
        "source_start": TASK_SPECS[task]["source_start"],
        "source_end": TASK_SPECS[task]["source_end"],
        "source_interaction_index": script["source_interaction_index"],
        "interaction_anchor": script["interaction_anchor"],
    }
    return trajectory, receipt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--calvin-code", type=Path, required=True)
    parser.add_argument("--source-split", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--tasks", nargs="+", default=list(TASK_SPECS))
    parser.add_argument("--motion-threshold", type=float, default=0.002)
    parser.add_argument(
        "--failure-storage",
        choices=("metadata_only", "full"),
        default="metadata_only",
        help="Failed scripted rollouts default to receipt-only persistence.",
    )
    parser.add_argument(
        "--emit-provisional-g",
        action="store_true",
        help="Opt in to experimental G/phase labels; native rollout storage is the default.",
    )
    parser.add_argument("--seed", type=int, default=20261020)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    unknown = sorted(set(args.tasks) - set(TASK_SPECS))
    if unknown:
        raise SystemExit(f"Unsupported tasks: {unknown}")
    args.calvin_code = args.calvin_code.resolve()
    args.source_split = args.source_split.resolve()
    args.out_dir = args.out_dir.resolve()
    manifest_path = args.out_dir / "collection_manifest.json"
    if manifest_path.exists():
        raise FileExistsError(f"Refusing to overwrite collection: {manifest_path}")

    calvin_models = args.calvin_code / "calvin_models"
    calvin_env = args.calvin_code / "calvin_env"
    sys.path[:0] = [calvin_env.as_posix(), calvin_models.as_posix()]
    import hydra  # noqa: PLC0415
    from omegaconf import OmegaConf  # noqa: PLC0415
    from calvin_env.envs.play_table_env import get_env  # noqa: PLC0415

    np.random.seed(args.seed)
    task_cfg_path = calvin_models / "conf/callbacks/rollout/tasks/new_playtable_tasks.yaml"
    task_cfg = OmegaConf.load(task_cfg_path)
    oracle = hydra.utils.instantiate(task_cfg)
    env = get_env(
        args.source_split,
        show_gui=False,
        obs_space={"rgb_obs": ["rgb_static", "rgb_gripper"], "depth_obs": []},
    )
    results = []
    try:
        for attempt_index, task in enumerate(args.tasks):
            attempt_id = f"{attempt_index:03d}_{task}_seed_{args.seed}"
            trajectory, receipt = collect_one(
                env,
                oracle,
                args.source_split,
                task,
                args.motion_threshold,
                emit_provisional_g=args.emit_provisional_g,
            )
            receipt.update({"attempt_id": attempt_id, "seed": args.seed})
            if not bool(receipt["oracle_success"]) and args.failure_storage == "metadata_only":
                receipt["failure_storage_mode"] = "metadata_only"
                receipt_path = persist_failure_metadata_only(
                    args.out_dir, attempt_id=attempt_id, receipt=receipt
                )
                receipt["path"] = None
                receipt["receipt_path"] = receipt_path.relative_to(args.out_dir).as_posix()
                receipt["sha256"] = None
            else:
                receipt["failure_storage_mode"] = "full_rate"
                path = persist_attempt(args.out_dir, attempt_id=attempt_id, trajectory=trajectory, receipt=receipt)
                receipt["path"] = path.relative_to(args.out_dir).as_posix()
                receipt["sha256"] = sha256_file(path)
            results.append(receipt)
            print(
                f"[collect] task={task} success={int(receipt['oracle_success'])} "
                f"steps={receipt['executed_steps']} path={receipt['path']}",
                flush=True,
            )
    finally:
        env.close()
        env.ownsPhysicsClient = False

    manifest = {
        "format": "calvin_scripted_expert_collection_v1",
        "provenance": {
            "collector": Path(__file__).resolve(),
            "calvin_code": args.calvin_code,
            "calvin_task_config": task_cfg_path,
            "calvin_task_config_sha256": sha256_file(task_cfg_path),
            "source_split": args.source_split,
            "source_kind": "official CALVIN relative-action scripts replayed from exact reset states",
            "observations_kind": "fresh simulator observations from this collection run",
            "acceptance_gate": "CALVIN get_task_info_for_set exact requested task",
        },
        "seed": args.seed,
        "motion_threshold": args.motion_threshold,
        "semantic_labels": {
            "candidate_g_emitted": bool(args.emit_provisional_g),
            "schema": "candidate_g_af_v1" if args.emit_provisional_g else "not_emitted",
            "role": "optional_derived_research_label_not_acceptance_or_distribution_gate",
        },
        "failure_storage": {
            "mode": args.failure_storage,
            "accepted_trajectories": "always_full_rate",
        },
        "tasks": args.tasks,
        "accepted": sum(bool(row["oracle_success"]) for row in results),
        "failed": sum(not bool(row["oracle_success"]) for row in results),
        "results": results,
    }
    args.out_dir.mkdir(parents=True, exist_ok=True)
    tmp_manifest = args.out_dir / ".collection_manifest.json.tmp"
    with open(tmp_manifest, "w", encoding="utf-8") as stream:
        json.dump(manifest, stream, indent=2, default=json_default)
        stream.write("\n")
    os.replace(tmp_manifest, manifest_path)
    print(json.dumps({"manifest": manifest_path, "accepted": manifest["accepted"], "failed": manifest["failed"]}, default=json_default))
    if manifest["failed"]:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
